#!/usr/bin/env node
// B-502 (D-370, D-372): the Proprietary token audit. It counts the distinct values per token family in a stylesheet
// (comments stripped), so polish and consolidation can say "21 -> 7 font sizes". A report, never a gate: it always
// exits 0 and no test holds its numbers.
//   node tools/token-audit.mjs                 page/styles.css, as text
//   node tools/token-audit.mjs <file> --json   any stylesheet, as JSON
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Colour: a raw hex or colour function, or one of E.V.'s colour tokens (generated by page/theme.js, D-268).
const COLOUR =
  /(#[0-9a-fA-F]{3,8}\b|(?:rgba?|hsla?|color-mix|lch|oklch)\((?:[^()]|\([^()]*\))*\)|var\(--(?:bg|chrome|surface|hover|line2?|text|quiet|faint|her2?|on-her|av[12]|sem-\w+|sunken|raised|do|do-ink|att|urg|glass2?|ink2?|soft|chip|accent[\w-]*|violet[\w-]*|plum[\w-]*|warn[\w-]*|bad[\w-]*|info[\w-]*|card|focus)\))/g;

const tally = () => new Map();
const add = (m, k, n = 1) => m.set(k, (m.get(k) || 0) + n);
const family = m => {
  const values = [...m.entries()].sort((a, b) => b[1] - a[1]).map(([value, uses]) => ({ value, uses }));
  return { distinct: values.length, uses: values.reduce((s, v) => s + v.uses, 0), values };
};
const all = (re, s) => [...s.matchAll(re)];

/** The audit of one stylesheet's text: {families: {name: {distinct, uses, values}}, counts: {...}}. */
export function audit(css) {
  const s = String(css).replace(/\/\*[\s\S]*?\*\//g, '');
  const decls = all(/([a-zA-Z-]+)\s*:\s*([^;{}]+)/g, s).map(m => [m[1], m[2]]);
  const f = {
    colours: tally(),
    washes: tally(),
    fontSizes: tally(),
    fontWeights: tally(),
    lineHeights: tally(),
    letterSpacing: tally(),
    spacing: tally(),
    radii: tally(),
    durations: tally(),
    easings: tally(),
    shadows: tally(),
    zIndex: tally(),
    mediaQueries: tally(),
  };
  for (const m of all(COLOUR, s)) add(f.colours, m[1].replace(/\s+/g, ''));
  for (const m of all(/rgba\(var\(--tint\),\s*([0-9.]+)\)/g, s)) add(f.washes, m[1]);
  for (const [p, v] of decls) {
    if (p === 'font-size' || p === 'font')
      for (const m of all(/calc\(\s*([0-9.]+)px\s*\*\s*var\(--ts\)\)|([0-9.]+(?:px|rem|em))/g, v))
        add(f.fontSizes, m[1] ? m[1] + 'px' : m[2]);
    if (p === 'font-weight') add(f.fontWeights, v.trim());
    if (p === 'line-height') add(f.lineHeights, v.trim());
    if (p === 'font') {
      const w = /^\s*(\d{3})/.exec(v);
      if (w) add(f.fontWeights, w[1]);
      const lh = /\)\s*\/\s*([0-9.]+[a-z]*)/.exec(v);
      if (lh) add(f.lineHeights, lh[1]);
    }
    if (p === 'letter-spacing') add(f.letterSpacing, v.trim());
    if (/^(padding|margin|gap|row-gap|column-gap)(-\w+)?$/.test(p))
      for (const m of all(/(?<![\w.(-])(-?[0-9.]+px)/g, v)) add(f.spacing, m[1].replace(/^-+/, ''));
    if (p.includes('radius')) for (const m of all(/([0-9.]+(?:px|%)|var\(--[\w-]+\))/g, v)) add(f.radii, m[1]);
    if (p.startsWith('transition') || p.startsWith('animation')) {
      for (const m of all(/(?<![\w.])([0-9]*\.?[0-9]+m?s)\b/g, v)) add(f.durations, m[1]);
      for (const m of all(/(cubic-bezier\([^)]*\)|ease-in-out|ease-out|ease-in|\bease\b|linear|var\(--ease\))/g, v))
        add(f.easings, m[1]);
    }
    if (p === 'box-shadow') add(f.shadows, v.trim().replace(/\s+/g, ' '));
    if (p === 'z-index') add(f.zIndex, v.trim());
  }
  for (const m of all(/@media\s*([^{]+)/g, s)) add(f.mediaQueries, m[1].replace(/\s+/g, ''));
  const count = needle => s.split(needle).length - 1;
  return {
    families: Object.fromEntries(Object.entries(f).map(([k, m]) => [k, family(m)])),
    counts: {
      important: count('!important'),
      ruleBlocks: all(/([^{}]+)\{/g, s).length,
      customProperties: new Set(all(/(--[\w-]+)\s*:/g, s).map(m => m[1])).size,
      keyframes: all(/@keyframes\s+([\w-]+)/g, s).length,
      layer: count('@layer'),
      where: count(':where('),
      focusVisible: count('focus-visible'),
      reducedMotion: count('prefers-reduced-motion'),
    },
  };
}

const LABELS = {
  colours: 'colour expressions',
  washes: 'alpha washes on --tint',
  fontSizes: 'font sizes',
  fontWeights: 'font weights',
  lineHeights: 'line heights',
  letterSpacing: 'letter spacing',
  spacing: 'spacing px (padding, margin, gap)',
  radii: 'radii',
  durations: 'durations',
  easings: 'easings',
  shadows: 'box shadows',
  zIndex: 'z-index',
  mediaQueries: 'media queries',
};

/** The audit as text: one line per family with its counts, then its values by use. */
export function report(a, { file = 'page/styles.css', top = 12 } = {}) {
  const lines = [`Token audit of ${file} (a report, never a gate)`];
  for (const [k, label] of Object.entries(LABELS)) {
    const fam = a.families[k];
    const shown = fam.values.slice(0, top).map(v => `${v.value} x${v.uses}`);
    const more = fam.values.length > top ? `, ... ${fam.values.length - top} more` : '';
    lines.push(`${label}: ${fam.distinct} distinct, ${fam.uses} uses`, `  ${shown.join(', ')}${more}`);
  }
  const c = a.counts;
  lines.push(
    `!important: ${c.important}; rule blocks: ${c.ruleBlocks}; custom properties defined: ${c.customProperties}; ` +
      `keyframes: ${c.keyframes}; @layer: ${c.layer}; :where(): ${c.where}; :focus-visible: ${c.focusVisible}; ` +
      `reduced motion: ${c.reducedMotion}`
  );
  return lines.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const file = args.find(a => !a.startsWith('--')) || 'page/styles.css';
  const a = audit(fs.readFileSync(path.resolve(ROOT, file), 'utf8'));
  console.log(args.includes('--json') ? JSON.stringify({ file, ...a }, null, 1) : report(a, { file }));
}
